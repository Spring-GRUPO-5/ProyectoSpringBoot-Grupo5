SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS imagen CASCADE;
DROP TABLE IF EXISTS producto CASCADE;
DROP TABLE IF EXISTS categoria CASCADE;
DROP TABLE IF EXISTS proveedor CASCADE;
DROP TABLE IF EXISTS cliente CASCADE;

CREATE TABLE cliente (
                         id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre varchar(60) NOT NULL,
                         apellido varchar(60) NOT NULL,
                         telefono varchar(20) NOT NULL,
                         email varchar(150) NOT NULL UNIQUE,
                         fecha_nacimiento date NOT NULL,
                         fecha_alta timestamp NOT NULL DEFAULT current_timestamp,
                         CONSTRAINT ck_cliente_fecha_nacimiento CHECK(fecha_nacimiento < current_date)
);

CREATE TABLE proveedor (
                           id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nombre varchar(60) NOT NULL,
                           apellido varchar(60),
                           telefono varchar(20) NOT NULL,
                           email varchar(150) NOT NULL UNIQUE
);

CREATE TABLE categoria (
                           id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nombre varchar(100) NOT NULL UNIQUE
);

CREATE TABLE producto (
                          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre varchar(150) NOT NULL,
                          cantidad integer NOT NULL,
                          precio numeric(10,2) NOT NULL,
                          categoria_id bigint NOT NULL,
                          proveedor_id bigint NOT NULL,
                          CONSTRAINT fk_producto_proveedor FOREIGN KEY(proveedor_id) REFERENCES proveedor(id),
                          CONSTRAINT fk_producto_categoria FOREIGN KEY(categoria_id) REFERENCES categoria(id),
                          CONSTRAINT ck_producto_cantidad CHECK(cantidad >= 0),
                          CONSTRAINT ck_producto_precio CHECK(precio >= 0)
);

CREATE TABLE imagen (
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        producto_id bigint NOT NULL,
                        imagen_url varchar(500) NOT NULL,
                        CONSTRAINT fk_imagen_producto FOREIGN KEY (producto_id) REFERENCES producto(id) ON DELETE CASCADE
);

