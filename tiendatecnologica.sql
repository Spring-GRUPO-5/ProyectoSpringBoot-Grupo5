-- Consultar productos con categoria y proveedor
SELECT
    p.id,
    p.nombre AS producto,
    p.cantidad,
    p.precio,
    c.nombre AS categoria,
    pr.nombre || ' ' || pr.apellido AS proveedor
FROM producto p
INNER JOIN categoria c ON p.categoria_id = c.id
INNER JOIN proveedor pr ON p.proveedor_id = pr.id
ORDER BY p.id;


